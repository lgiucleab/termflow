// Built-in themes: UI design tokens plus the terminal palette. Palettes of the open (MIT) projects
// Nord, Gruvbox and Catppuccin are used by colour value; names appear as plain text only.
import type { ITheme } from "@xterm/xterm";

export interface Theme {
  id: string;
  name: string;
  light: boolean;
  ui: {
    /** Window layer behind the raised panels. */
    deep: string;
    /** Panel background (timeline, sidebar cards, dialogs). */
    bg: string;
    surface: string;
    surface2: string;
    border: string;
    text: string;
    muted: string;
    /** Decorative text (meta, placeholders); not held to AA. */
    faint: string;
    accent: string;
    success: string;
    warning: string;
    danger: string;
  };
  terminal: ITheme;
}

